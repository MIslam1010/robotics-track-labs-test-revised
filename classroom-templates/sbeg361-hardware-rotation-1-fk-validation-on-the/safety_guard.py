"""Independent software safety layer for the course arm (Hardware rotation 1, Week 8).

Students do NOT edit this file.  Both backends (`sim_arm.SimArm` and `vendor_arm.VendorArm`) pass every
command through a `SafetyGuard` BEFORE it reaches the servos, whatever the student code does:

  * software joint limits  = hardware limits minus `limit_margin_deg` (10 deg, shared course-arm checklist rule 1);
  * command rate limit     = `speed_fraction` x rated speed (25 % in rotation 1, checklist rule 3), with 20 % tolerance for timing
                             jitter, computed from consecutive commands;
  * a stop is LATCHED: after `trip()` (e-stop, limit or speed violation) no motion command is accepted until an
    operator calls `reset()`.

This is "defence in depth": the planning check you write in `starter.check_plan` is the first barrier, this guard
is the second, and the hardware emergency stop (power switch) is the third.  Values are illustrative.
"""
import numpy as np

HW_LIMITS_DEG = np.array([(-165, 165)] * 5 + [(-175, 175)], float)   # model angles (course_arm_model.py)
RATED_SPEED_DEG_S = 160.0


class SafetyViolation(RuntimeError):
    """Raised when a command would leave the software limits or exceed the speed cap."""


class SafetyGuard:
    def __init__(self, offsets_deg, hw_limits_deg=HW_LIMITS_DEG, limit_margin_deg=10.0,
                 rated_speed_deg_s=RATED_SPEED_DEG_S, speed_fraction=0.25, tolerance=1.2):
        self.offsets = np.asarray(offsets_deg, float)
        lim = np.asarray(hw_limits_deg, float)
        self.soft_limits = np.column_stack([lim[:, 0] + limit_margin_deg, lim[:, 1] - limit_margin_deg])
        self.speed_cap = speed_fraction * rated_speed_deg_s
        self.tolerance = tolerance
        self.tripped = False
        self.reason = ""
        self._last = None          # (t, q_servo) of the last accepted command

    def trip(self, reason):
        self.tripped = True
        self.reason = reason

    def reset(self, t=None, q_servo_deg=None):
        """Operator reset after a stop; optionally restart the rate check from the current pose."""
        self.tripped = False
        self.reason = ""
        q = None if q_servo_deg is None else np.asarray(q_servo_deg, float)
        # a non-finite reading (communication glitch) cannot seed the rate check
        self._last = (float(t), q.copy()) if q is not None and np.all(np.isfinite(q)) else None

    def check(self, t, q_servo_deg):
        """Return the command unchanged if it is safe; otherwise trip and raise SafetyViolation."""
        q = np.asarray(q_servo_deg, float)
        if self.tripped:
            raise SafetyViolation(f"guard is latched ({self.reason}); operator reset required")
        if q.shape != (6,) or not np.all(np.isfinite(q)):
            self.trip("command is not six finite joint angles")
            raise SafetyViolation(self.reason)
        qm = q - self.offsets
        bad = (qm < self.soft_limits[:, 0]) | (qm > self.soft_limits[:, 1])
        if np.any(bad):
            j = int(np.argmax(bad)) + 1
            self.trip(f"joint {j} command {qm[j - 1]:.1f} deg (model) outside software limits")
            raise SafetyViolation(self.reason)
        if self._last is not None:
            dt = max(float(t) - self._last[0], 1e-3)       # same or earlier time stamp: no free jump
            rate = np.abs(q - self._last[1]) / dt
            if np.any(rate > self.tolerance * self.speed_cap + 1e-9):
                j = int(np.argmax(rate)) + 1
                self.trip(f"joint {j} command rate {rate[j - 1]:.1f} deg/s > cap {self.speed_cap:.1f} deg/s")
                raise SafetyViolation(self.reason)
        self._last = (float(t), q.copy())
        return q
