def test_safety_guard_limits_rate_and_latch():
    g = SafetyGuard(OFF)
    g.check(0.0, OFF + 10)
    with pytest.raises(SafetyViolation):
        g.check(0.01, OFF + 11)                                       # 100 deg/s > 1.2 x 40
    with pytest.raises(SafetyViolation):
        g.check(5.0, OFF)                                             # latched until reset
    g.reset()
    with pytest.raises(SafetyViolation):
        g.check(6.0, OFF + np.array([0, 0, 0, 160, 0, 0]))           # outside +-155 deg (model)
    g.reset()
    assert np.allclose(g.check(7.0, OFF + 154), OFF + 154)


def test_vendor_adapter_with_fake_sdk():
    from vendor_arm import VendorArm

    class FakeSDK:
        def __init__(self):
            self.sent, self.stops, self.q = [], 0, [0.0, 90.0, 0.0, 90.0, 0.0, 0.0]

        def send_angles(self, q, speed):
            self.sent.append((list(q), speed))
            self.q = list(q)

        def get_angles(self):
            return list(self.q)

        def stop(self):
            self.stops += 1

    sdk = FakeSDK()
    arm = VendorArm(offsets_deg=OFF, sdk=sdk).connect()
    with pytest.raises(SafetyViolation):          # the guard is seeded at connect: no instant jump
        arm.send(OFF + 1)
    assert sdk.stops == 1 and len(sdk.sent) == 0
    arm.reset()
    arm.wait_until(arm.time() + 0.1)              # 1 deg in 0.1 s = 10 deg/s < 40 deg/s cap
    assert arm.send(OFF + 1) and sdk.sent[-1][1] == 25
    assert np.allclose(arm.read(), OFF + 1)
    with pytest.raises(SafetyViolation):
        arm.send(OFF + np.array([0, 170, 0, 0, 0, 0]))
    assert sdk.stops == 2 and len(sdk.sent) == 1 and arm.send(OFF) is False


