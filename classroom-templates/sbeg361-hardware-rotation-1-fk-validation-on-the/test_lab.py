def fk_tool_mm(q_servo_deg, offsets=OFF):
    """Independent tool-point FK with modern_robotics (mm)."""
    pb = np.r_[np.asarray(P_TOOL, float), 1.0]
    q = np.deg2rad(np.atleast_2d(q_servo_deg) - offsets)
    return np.array([1e3 * (mr.FKinSpace(M, S, qi) @ pb)[:3] for qi in q])


