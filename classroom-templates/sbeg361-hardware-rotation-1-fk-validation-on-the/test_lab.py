def test_error_budget_matches_jacobian_columns():
    th = np.deg2rad(PLAN["poses_model_deg"]["P2"])
    r = lab.error_budget(M, S, th, P_TOOL)
    p = fk_tool_mm(np.asarray(PLAN["poses_model_deg"]["P2"], float) + OFF)[0] / 1e3
    J = mr.JacobianSpace(S, th)                                       # Week 9: velocity of the point p
    lever = np.linalg.norm(J[3:] + np.cross(J[:3].T, p).T, axis=0)
    assert np.allclose(r["lever_m"], lever, atol=1e-9)
    assert np.allclose(r["lever_m"], [0.21674, 0.20812, 0.20911, 0.12958, 0.10560, 0.0], atol=2e-5)
    assert np.isclose(r["rss_mm"], 0.617, atol=2e-3) and np.isclose(r["worst_mm"], 1.333, atol=2e-3)
    r2 = lab.error_budget(M, S, th, P_TOOL, dtheta_deg=[0, 1, 0, 0, 0, 0])
    assert np.isclose(r2["dp_mm"][1], 1e3 * lever[1] * np.pi / 180) and np.isclose(r2["worst_mm"], r2["dp_mm"][1])


