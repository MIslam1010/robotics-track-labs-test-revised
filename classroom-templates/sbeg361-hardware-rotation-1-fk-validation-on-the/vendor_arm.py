"""Thin adapter between the lab code and the vendor SDK of a course arm (hardware station, Week 8).

Students do NOT edit this file; the supervising TA runs it.  It exposes the same interface as `sim_arm.SimArm`
(connect, time, wait_until, send, read, stop, reset, close) and routes EVERY motion command through
`safety_guard.SafetyGuard` (software limits 10 deg inside the hardware limits, speed cap 25 % of rated, latched stop).

The adapter is written for a myCobot-280-class arm and its Python SDK (`pymycobot`), whose robot object provides
calls to send a list of six joint angles with a speed, to read the six joint angles and to stop motion.  Method
names and the import path differ between SDK versions: check them in the installed version
(`python -c "import pymycobot, inspect; print(pymycobot.__version__)"`) and adjust `_open_sdk` and the three
`_sdk_*` methods ONLY (the TA does this once per arm at commissioning).  Any other SDK object with the methods
`send_angles(list, speed_percent)`, `get_angles()` and `stop()` can be passed directly as `sdk=`.

Angles are SERVO degrees, as reported by the SDK.  Time is real time (time.perf_counter).
"""
import time as _time

import numpy as np

from safety_guard import SafetyGuard


class VendorArm:
    def __init__(self, port=None, baud=115200, offsets_deg=(0, 90, 0, 90, 0, 0), sdk=None, guard=None,
                 speed_percent=25):
        self.port, self.baud = port, baud
        self.offsets = np.asarray(offsets_deg, float)
        self.guard = guard if guard is not None else SafetyGuard(self.offsets)
        self.speed_percent = int(speed_percent)       # SDK speed setting; the guard caps the command rate
        self._sdk = sdk
        self._t0 = None
        self._last_read = None
        self.stopped = False

    # ------------------------------------------------------------------ SDK glue (adjust per SDK version)
    def _open_sdk(self):
        try:                                     # newer pymycobot versions
            from pymycobot import MyCobot280 as _Arm
        except ImportError:
            try:                                 # older versions
                from pymycobot.mycobot import MyCobot as _Arm
            except ImportError as exc:           # pragma: no cover - depends on the lab PC
                raise RuntimeError("vendor SDK not installed on this PC: use the simulation station "
                                   "(python run_session.py --backend sim) or ask the TA") from exc
        return _Arm(self.port, self.baud)

    def _sdk_send(self, q):
        self._sdk.send_angles([float(x) for x in q], self.speed_percent)

    def _sdk_read(self):
        q = self._sdk.get_angles()
        if q is None or len(q) != 6:            # some SDKs return -1 / [] on a communication glitch
            return None
        return np.asarray(q, float)

    def _sdk_stop(self):
        self._sdk.stop()

    # ------------------------------------------------------------------ common interface
    def connect(self):
        if self._sdk is None:
            self._sdk = self._open_sdk()
        self._t0 = _time.perf_counter()
        q = self.read()
        self.guard.reset(self.time(), q)         # seed the rate check with the current pose
        return self

    def close(self):
        self._sdk = None

    def time(self):
        return _time.perf_counter() - self._t0

    def wait_until(self, t):
        while True:
            dt = t - self.time()
            if dt <= 0:
                return
            _time.sleep(min(dt, 0.005))

    def send(self, q_servo_deg):
        if self.stopped:
            return False
        try:
            q = self.guard.check(self.time(), q_servo_deg)
        except Exception:
            self.stop()
            raise
        self._sdk_send(q)
        return True

    def read(self):
        q = self._sdk_read()
        if q is None:                           # repeat the last good reading and let the log show it
            return self._last_read.copy() if self._last_read is not None else np.full(6, np.nan)
        self._last_read = q
        return q.copy()

    def stop(self):
        self._sdk_stop()
        self.stopped = True
        self.guard.trip("operator stop")

    def reset(self):
        self.stopped = False
        q = self.read()
        self.guard.reset(self.time(), q)
