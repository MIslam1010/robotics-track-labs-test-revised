def test_run_logged_on_emulator_and_guard():
    arm = SimArm("S1", offsets_deg=OFF).connect()
    q0 = arm.read()
    q1 = q0 + np.array([10, -8, 6, 0, 0, 5])
    t, q = lab.smooth_segments(np.vstack([q0, q1]), 1.5, 50, t_hold=1.0)
    log = lab.run_logged(arm, t, q)
    assert log["aborted"] is None and not np.any(log["stop"])
    assert log["meas"].shape == q.shape
    assert np.allclose(log["meas"][-1], q1, atol=1.0)            # settles within the droop / noise
    # a command jump far above the 40 deg/s cap is refused by the guard; run_logged stops and keeps logging
    arm2 = SimArm("S1", offsets_deg=OFF).connect()
    p0 = arm2.read()
    t2 = np.arange(20) * 0.02
    q2 = np.repeat(p0[None], 20, axis=0)
    q2[5:, 0] += 30.0                                            # 30 deg in 20 ms = 1500 deg/s
    log2 = lab.run_logged(arm2, t2, q2)
    assert log2["aborted"] and "rate" in log2["aborted"]
    assert np.array_equal(log2["stop"][:5], [0] * 5) and np.all(log2["stop"][5:] == 1)
    assert np.allclose(log2["meas"][-1], p0, atol=1.0)            # did not follow the jump (droop only)


